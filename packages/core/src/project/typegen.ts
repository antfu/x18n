import type { ResolvedConfig } from '../types/config'
import type { TypegenContext, TypegenFile, TypegenTarget, TypegenTree } from '../types/plugin'
import { keyJoiner } from '../keys'

const header = '// Generated by `x18n typegen`. Do not edit.\n\n'

function put(tree: TypegenTree, path: readonly string[], value: string): void {
  let node = tree
  for (const part of path.slice(0, -1)) {
    const next = node[part]
    // A key that is both a value and a parent keeps the parent.
    if (typeof next === 'object') {
      node = next
    }
    else {
      const created: TypegenTree = {}
      node[part] = created
      node = created
    }
  }
  const last = path.at(-1)!
  if (typeof node[last] !== 'object')
    node[last] = value
}

/** A message of the source locale, by namespace (undefined in a project without namespaces) and key path. */
export interface TypegenEntry {
  readonly namespace: string | undefined
  readonly path: readonly string[]
  readonly value: unknown
}

/** Orders by UTF-16 code units, the same in every locale. */
function byName(a: { readonly name: string }, b: { readonly name: string }): number {
  return a.name < b.name
    ? -1
    : a.name > b.name
      ? 1
      : 0
}

/** The messages of the source locale as trees per namespace, for the `typegen` hook of a plugin. */
export function typegenContext(config: ResolvedConfig, entries: readonly TypegenEntry[]): TypegenContext {
  const defaultNamespace = config.namespace.default
  const trees = new Map<string, TypegenTree>()
  for (const entry of entries) {
    if (typeof entry.value !== 'string' || entry.path.length === 0)
      continue
    const namespace = entry.namespace ?? defaultNamespace ?? ''
    let tree = trees.get(namespace)
    if (!tree) {
      tree = {}
      trees.set(namespace, tree)
    }
    // Literal keys are one segment, as they are written in code.
    put(tree, config.keySeparator === false
      ? [
          entry.path.join(keyJoiner(false)),
        ]
      : entry.path, entry.value)
  }
  return {
    config,
    defaultNamespace,
    namespaces: [...trees].map(([name, tree]) => ({ name, tree })).sort(byName),
  }
}

/** The file `typegen` writes, or nothing when it's off or no plugin can write it. */
export function renderTypegen(config: ResolvedConfig, target: TypegenTarget | undefined, context: () => TypegenContext): TypegenFile | undefined {
  if (!config.typegen || config.typegen.output === undefined || !target)
    return undefined
  return {
    path: config.typegen.output,
    target: target.id,
    content: `${header}${target.render(context())}`,
  }
}
