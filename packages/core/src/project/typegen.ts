import type { ResolvedConfig } from '../types/config'
import type { Plugin, TypegenContext, TypegenFile, TypegenTree } from '../types/plugin'

const header = '// Generated by `x18n typegen`. Do not edit.\n\n'

function put(tree: TypegenTree, path: readonly string[], value: string): void {
  let node = tree
  for (const part of path.slice(0, -1)) {
    const next = node[part]
    // A key that is both a value and a parent keeps the parent.
    if (typeof next === 'object') {
      node = next
    }
    else {
      const created: TypegenTree = {}
      node[part] = created
      node = created
    }
  }
  const last = path.at(-1)!
  if (typeof node[last] !== 'object')
    node[last] = value
}

/** The messages of the source locale as trees per namespace, for the `typegen` hook of a plugin. */
export function typegenContext(config: ResolvedConfig, keys: readonly string[], valueOf: (key: string) => unknown): TypegenContext {
  const { separator, default: defaultNamespace } = config.namespace
  const namespaced = separator !== undefined && defaultNamespace !== undefined
  const trees = new Map<string, TypegenTree>()
  for (const key of keys) {
    const value = valueOf(key)
    if (typeof value !== 'string')
      continue
    const at = namespaced && separator
      ? key.indexOf(separator)
      : -1
    const namespace = at === -1
      ? defaultNamespace ?? ''
      : key.slice(0, at)
    const rest = at === -1
      ? key
      : key.slice(at + (separator || '').length)
    let tree = trees.get(namespace)
    if (!tree) {
      tree = {}
      trees.set(namespace, tree)
    }
    put(tree, config.keySeparator === false
      ? [rest]
      : rest.split(config.keySeparator), value)
  }
  return {
    config,
    defaultNamespace,
    namespaces: [...trees].map(([name, tree]) => ({ name, tree })).sort((a, b) => a.name.localeCompare(b.name)),
  }
}

/** The file `typegen` writes, or nothing when it's off or no plugin can write it. The last plugin with a target wins. */
export function renderTypegen(config: ResolvedConfig, plugins: readonly Plugin[], context: () => TypegenContext): TypegenFile | undefined {
  if (!config.typegen)
    return undefined
  const target = plugins.flatMap(plugin => plugin.typegen ?? []).at(-1)
  return target && {
    path: config.typegen.output,
    target: target.id,
    content: `${header}${target.render(context())}`,
  }
}
