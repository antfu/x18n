import type { UserConfig } from '@x18n/core'
import { describe, expect, it } from 'vitest'
import { createTestProject, json } from './_utils'

const flat: UserConfig = {
  presets: ['i18next'],
  sourceLocale: 'en',
  typegen: true,
  resources: [
    { pattern: 'locales/{locale}.json' },
  ],
}

function stale(project: { analyze: () => { diagnostics: readonly { code: string, message: string }[] } }): string[] {
  return project.analyze().diagnostics.filter(d => d.code === 'typegen-stale').map(d => d.message)
}

describe('typegen', () => {
  it('is off by default', async () => {
    const { project } = await createTestProject({
      'tsconfig.json': '{}',
      'locales/en.json': json({ a: 'A' }),
    }, { ...flat, typegen: false })
    expect(project.typegen()).toBeUndefined()
    expect(stale(project)).toEqual([])
  })

  it('writes the source locale as the resources of i18next', async () => {
    const { project } = await createTestProject({
      'tsconfig.json': '{}',
      'locales/en.json': json({
        title: 'Hello',
        nested: { a: 'Hi {{name}}' },
      }),
      'locales/fr.json': json({ title: 'Salut', extra: 'Only here' }),
    }, flat)
    const file = project.typegen()!
    expect(file.path).toBe('x18n.d.ts')
    expect(file.target).toBe('i18next')
    expect(file.content).toContain('// Generated by `x18n typegen`. Do not edit.')
    expect(file.content).toContain('declare module \'i18next\'')
    expect(file.content).toContain('"title": "Hello"')
    expect(file.content).toContain('"a": "Hi {{name}}"')
    expect(file.content).not.toContain('Only here')
  })

  it('keeps one tree per namespace', async () => {
    const { project } = await createTestProject({
      'tsconfig.json': '{}',
      'locales/en/translation.json': json({ a: 'A' }),
      'locales/en/admin.json': json({ b: 'B' }),
    }, {
      ...flat,
      resources: [
        { pattern: 'locales/{locale}/{namespaces}.json' },
      ],
    })
    const { content } = project.typegen()!
    expect(content).toContain('defaultNS: "translation"')
    expect(content).toMatch(/"admin": \{\s+"b": "B"/)
    expect(content).toMatch(/"translation": \{\s+"a": "A"/)
  })

  it('names a custom output and flat keys', async () => {
    const { project } = await createTestProject({
      'tsconfig.json': '{}',
      'locales/en.json': json({ 'a.b': 'A' }),
    }, {
      ...flat,
      keySeparator: false,
      typegen: { output: 'src/x18n.d.ts' },
    })
    const file = project.typegen()!
    expect(file.path).toBe('src/x18n.d.ts')
    expect(file.content).toContain('keySeparator: false')
    expect(file.content).toContain('"a.b": "A"')
  })

  it('needs TypeScript', async () => {
    const { project } = await createTestProject({
      'locales/en.json': json({ a: 'A' }),
    }, flat)
    expect(project.typegen()).toBeUndefined()
    expect(stale(project)).toEqual([])
    const { project: installed } = await createTestProject({
      'node_modules/typescript/package.json': '{}',
      'locales/en.json': json({ a: 'A' }),
    }, flat)
    expect(installed.typegen()).toBeDefined()
  })

  it('needs a preset with a target', async () => {
    const { project } = await createTestProject({
      'tsconfig.json': '{}',
      'locales/en.json': json({ a: 'A' }),
    }, { ...flat, presets: [] })
    expect(project.typegen()).toBeUndefined()
    expect(stale(project)).toEqual([])
  })

  it('reports a missing or stale file until it matches', async () => {
    const { project, files } = await createTestProject({
      'tsconfig.json': '{}',
      'locales/en.json': json({ a: 'A' }),
    }, flat)
    expect(stale(project)).toEqual(['x18n.d.ts does not exist. Run `x18n typegen`.'])
    const { content } = project.typegen()!
    files.set('x18n.d.ts', `${content}// edited\n`)
    await project.update([
      { type: 'create', path: 'x18n.d.ts' },
    ])
    expect(stale(project)).toEqual(['x18n.d.ts is out of date. Run `x18n typegen`.'])
    files.set('x18n.d.ts', content)
    await project.update([
      { type: 'change', path: 'x18n.d.ts' },
    ])
    expect(stale(project)).toEqual([])
    files.set('locales/en.json', json({ a: 'Changed' }))
    await project.update([
      { type: 'change', path: 'locales/en.json' },
    ])
    expect(stale(project)).toEqual(['x18n.d.ts is out of date. Run `x18n typegen`.'])
  })
})
