/**
 * Writes the translated pages under `content/<locale>/` from the English pages and the
 * diglot records in `i18n/` (https://github.com/danielroe/diglot). A segment without a valid
 * record keeps its English text, marked `lang="en"`, so every locale mirrors the English tree.
 */
import type { TranslationRecord } from '@diglot/core'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'
import { applyNavigation, apply as applyTranslations, parse, render } from '@diglot/comark'
import { loadConfig, loadLocale, readSource } from '@diglot/store'

/** The URL prefix and content directory of each translated locale. */
function localeSlug(locale: string): string {
  return locale.toLowerCase()
}

/** The route of a content file: numeric prefixes, `.md` and `index` dropped. */
function routeOf(path: string): string {
  const parts = path.replace(/\.md$/, '').split('/').map(part => part.replace(/^\d+\./, ''))
  if (parts.at(-1) === 'index')
    parts.pop()
  return `/${parts.join('/')}`
}

/** Points links to English pages at the same page in the locale. Elements are `[tag, attrs, ...children]`. */
function localizeLinks(nodes: readonly unknown[], prefix: string, routes: Set<string>): void {
  for (const node of nodes) {
    if (!Array.isArray(node))
      continue
    const [, attrs, ...children] = node as [string, Record<string, unknown>, ...unknown[]]
    for (const name of ['href', 'to']) {
      const value = attrs[name]
      if (typeof value !== 'string' || !value.startsWith('/'))
        continue
      const path = value.split(/[?#]/)[0]!.replace(/\/$/, '') || '/'
      if (routes.has(path)) {
        attrs[name] = path === '/'
          ? `${prefix}${value.slice(1)}`
          : `${prefix}${value}`
      }
    }
    localizeLinks(children, prefix, routes)
  }
}

/** Drops the `lang` of table cells, which markdown tables cannot carry. */
function unmarkCells(nodes: readonly unknown[]): void {
  for (const node of nodes) {
    if (!Array.isArray(node))
      continue
    if (node[0] === 'td' || node[0] === 'th')
      delete (node[1] as Record<string, unknown>).lang
    unmarkCells(node.slice(2))
  }
}

/** Inline code in markdown: a fence longer than any backtick run in `value`, padded where needed. */
function inlineCode(value: string): string {
  const longest = Math.max(0, ...Array.from(value.matchAll(/`+/g), m => m[0].length))
  const fence = '`'.repeat(longest + 1)
  const pad = value.startsWith('`') || value.endsWith('`')
    ? ' '
    : ''
  return `${fence}${pad}${value}${pad}${fence}`
}

/**
 * Renders a document. comark's renderer writes inline code that contains backticks (such as a
 * tagged template) with a fence that is too short, so such code is rendered as a token and written back here.
 */
async function renderDocument(doc: Awaited<ReturnType<typeof parse>>): Promise<string> {
  const codes: string[] = []
  const swap = (nodes: unknown[]): void => {
    for (const node of nodes) {
      // Code blocks (`pre`) render correctly.
      if (!Array.isArray(node) || node[0] === 'pre')
        continue
      if (node[0] === 'code' && node.length === 3 && typeof node[2] === 'string' && node[2].includes('`'))
        node[2] = `x18n-code-${codes.push(node[2]) - 1}`
      else
        swap(node.slice(2))
    }
  }
  swap(doc.nodes)
  return (await render(doc)).replace(/`x18n-code-(\d+)`/g, (_, i: string) => inlineCode(codes[Number(i)]!))
}

/**
 * The translated pages of every locale, as paths relative to `docs/` with their content.
 * `pages` are the English pages (relative to `content/`) when they differ from the files on disk,
 * as when `generate.ts` has just rendered some of them.
 */
export async function translatedPages(pages: Map<string, string> = new Map()): Promise<Map<string, string>> {
  const config = await loadConfig(fileURLToPath(new URL('../i18n', import.meta.url)))
  const source = config.sources.find(s => s.name === 'docs')!
  const dir = `${source.dir}/`
  const snapshot = await readSource(source, config.root)
  const files = new Map(snapshot.files.map(f => [
    f.path.slice(dir.length),
    f.content,
  ]))
  for (const [path, content] of pages)
    files.set(path, content)

  const routes = new Set([
    ...files.keys(),
  ].filter(p => p.endsWith('.md')).map(routeOf))
  const outputs = new Map<string, string>()

  for (const locale of config.locales) {
    const slug = localeSlug(locale)
    const records = await loadLocale(config.root, locale)
    const lookup = (segment: { hash: string }): TranslationRecord | undefined => records.get(segment.hash)
    const banner = `<!-- Generated by docs/scripts/generate.ts from docs/i18n/${locale}. Do not edit. -->`

    const name = new Intl.DisplayNames([locale], { type: 'language' }).of(locale) ?? locale
    outputs.set(`content/${slug}/.navigation.yml`, `title: ${name}\n`)
    for (const [path, content] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
      const target = `content/${slug}/${path}`
      if (path.endsWith('.navigation.yml')) {
        outputs.set(target, applyNavigation(content, lookup, { file: `${dir}${path}` }).source)
        continue
      }
      const doc = await parse(content)
      const { doc: translated } = await applyTranslations(doc, lookup, {
        file: `${dir}${path}`,
        spanSources: false,
        onSegment(event) {
          if (event.outcome === 'missing' || event.outcome === 'rejected')
            event.target?.setAttribute('lang', 'en')
        },
      })
      localizeLinks(translated.nodes, `/${slug}`, routes)
      unmarkCells(translated.nodes)
      const expected = structuredClone(translated.nodes)
      const rendered = await renderDocument(translated)
      // Rendering must not change the document, or the page would show something else than its records.
      if (!isDeepStrictEqual((await parse(rendered)).nodes, expected))
        throw new Error(`${target}: the rendered page does not parse back to the translated document`)
      outputs.set(target, rendered.replace(/^(---\n[\s\S]*?\n---\n)?/, head => `${head}\n${banner}\n`))
    }
  }
  return outputs
}

/** The content directories `translatedPages` owns; files there that it does not write are stale. */
export async function translatedDirs(): Promise<string[]> {
  const config = await loadConfig(fileURLToPath(new URL('../i18n', import.meta.url)))
  return config.locales.map(locale => `content/${localeSlug(locale)}`)
}
